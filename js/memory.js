// 遗忘曲线（简化艾宾浩斯）
// 答对：level + 1，按间隔表推后下次复习时间
// 答错：level 归零，10 分钟后重新复习（调度见 storage.recordAnswer）
const Memory = {
  INTERVALS: [
    10 * 60 * 1000, // 0: 10 分钟
    60 * 60 * 1000, // 1: 1 小时
    24 * 3600 * 1000, // 2: 1 天
    2 * 24 * 3600 * 1000, // 3: 2 天
    4 * 24 * 3600 * 1000, // 4: 4 天
    7 * 24 * 3600 * 1000, // 5: 7 天
    15 * 24 * 3600 * 1000, // 6: 15 天
  ],
  MAX_LEVEL: 6,

  // 薄弱权重：错得越多、等级越低的字越容易被抽中
  weakWeight(record) {
    return 1 + record.wrong * 2 + Math.max(0, 5 - record.level);
  },
};
